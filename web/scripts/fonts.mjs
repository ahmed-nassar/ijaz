// Copies the self-hosted IBM Plex Sans Arabic subsets into public/fonts and writes the
// matching @font-face rules to lib/font-face.generated.ts (inlined into the page).
// Only the Arabic, Latin and Latin Extended (Turkish) subsets are kept; the browser downloads
// a subset only when the page uses a character from its unicode-range.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(root, "node_modules/@fontsource/ibm-plex-sans-arabic");
const keep = ["arabic", "latin", "latin-ext"];
const weights = ["400", "600"];

mkdirSync(join(root, "public/fonts"), { recursive: true });
copyFileSync(join(pkg, "LICENSE"), join(root, "public/fonts/LICENSE-IBM-Plex-OFL.txt"));
const rules = [];
for (const weight of weights) {
  const css = readFileSync(join(pkg, `${weight}.css`), "utf8");
  for (const block of css.match(/\/\*[^*]*\*\/\s*@font-face\s*{[^}]*}/g) ?? []) {
    const subset = block.match(/\/\*\s*ibm-plex-sans-arabic-([a-z-]+)-\d+-normal\s*\*\//)?.[1];
    if (!subset || !keep.includes(subset)) continue;
    const file = `ibm-plex-sans-arabic-${subset}-${weight}-normal.woff2`;
    copyFileSync(join(pkg, "files", file), join(root, "public/fonts", file));
    const range = block.match(/unicode-range:\s*([^;]+);/)[1];
    rules.push(
      `@font-face{font-family:"IBM Plex Sans Arabic";font-style:normal;font-display:swap;font-weight:${weight};` +
        `src:url(/fonts/${file}) format("woff2");unicode-range:${range}}`,
    );
  }
}
if (rules.length !== keep.length * weights.length) throw new Error(`expected ${keep.length * weights.length} font rules, got ${rules.length}`);
writeFileSync(
  join(root, "lib/font-face.generated.ts"),
  `// Generated by scripts/fonts.mjs. Do not edit.\nexport const FONT_FACE = ${JSON.stringify(rules.join("\n"))};\n`,
);
console.log(`fonts: ${rules.length} subsets copied`);
